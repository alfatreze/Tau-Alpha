#!/usr/bin/env python3
"""Read-only, pinned-revision code-origin measurement. Writes evidence, not Git state.

Usage: python3 measure.py --repo /path/to/tau-alpha --out /path/to/evidence
SLOC means nonblank, non-comment physical lines, not tokens or compiled bytes.
Copy-aware blame identifies last textual origin, NOT exclusive creative ownership.
"""
import argparse
import collections
import concurrent.futures
import csv
import difflib
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tokenize
import io

EXTS = {'.c', '.cpp', '.h', '.inc', '.S', '.s', '.v', '.sv', '.vh', '.svh', '.py', '.sh', '.ps1', '.tcl', '.ld', '.sdc'}
BASE = '7ef8f0fb84abd4ae5a6a187805fd910351ae57dc'
GENERATED = {'src/fpga/core/font_rom.v', 'src/fpga/core/eq_coefs.vh', 'sim/common/test_mp3.h', 'sim/common/test_mp3_128.h', 'archive/qr_encoder/qr_tables.h'}
VENDOR_MIXED = {'src/fpga/core/data_loader.sv', 'src/fpga/core/sound_i2s.v', 'src/fpga/core/sync_fifo.v', 'src/fpga/rtl/mem/sdram_fb.sv'}


def git(repo, *args):
    return subprocess.check_output(['git', '-C', str(repo), *args], stderr=subprocess.PIPE).decode('utf-8', 'replace')


def is_source(p):
    return Path(p).suffix in EXTS or Path(p).name in {'Makefile', 'Umakefil'}


def bucket(p, s):
    if p.startswith('third_party/'):
        return 'vendor'
    if p == 'src/fpga/rtl/VexRiscv_Full.v':
        return 'vendor_generated'
    if p.startswith('src/fpga/apf/') or p == 'src/fpga/core/core_bridge_cmd.v':
        return 'framework'
    if p in VENDOR_MIXED:
        return 'vendor_mixed'
    # Exact generator notices only; mentions of generated data in prose do not qualify.
    if p in GENERATED or re.search(r'(?im)^\s*(?:/\*|//|#)\s*(?:GENERATED by|Auto-generated|Generated by)', s[:600]):
        return 'generated'
    if p.startswith('src/fpga/core/mf_pllbase/') or p == 'src/fpga/core/mf_pllbase_mclk.v':
        return 'vendor_generated'
    if p.startswith('archive/'):
        return 'archive'
    if p.startswith('sim/') or p.startswith('tools/host/') or p == 'tools/triad/test_director.py':
        return 'test'
    if p.startswith('fw/'):
        return 'firmware'
    if p.startswith('src/fpga/'):
        return 'rtl'
    return 'tooling'


def sloc_mask(p, s):
    lines = s.splitlines()
    if Path(p).suffix == '.py':
        flags = [False] * len(lines)
        try:
            for t in tokenize.generate_tokens(io.StringIO(s).readline):
                if t.type not in {tokenize.COMMENT, tokenize.NL, tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.ENDMARKER, tokenize.ENCODING}:
                    for i in range(t.start[0] - 1, min(t.end[0], len(lines))):
                        flags[i] = True
            return [flag and bool(line.strip()) for flag, line in zip(flags, lines)]
        except (tokenize.TokenError, IndentationError):
            pass
    hash_comments = Path(p).suffix in {'.sh', '.ps1', '.tcl', '.sdc', '.s', '.S'} or Path(p).name in {'Makefile', 'Umakefil'}
    if hash_comments:
        # Preserve C-preprocessor directives in preprocessed assembler.
        return [bool(x.strip()) and (not x.lstrip().startswith('#') or (Path(p).suffix == '.S' and bool(re.match(r'\s*#\s*(include|define|if|ifdef|ifndef|else|elif|endif|undef|error)\b', x)))) for x in lines]
    flags = []
    in_block = False
    for line in lines:
        out = []
        i = 0
        quote = None
        while i < len(line):
            pair = line[i:i+2]
            if in_block:
                if pair == '*/':
                    in_block = False
                    i += 2
                else:
                    i += 1
            elif quote:
                out.append(line[i])
                if line[i] == '\\' and i + 1 < len(line):
                    out.append(line[i+1])
                    i += 2
                else:
                    if line[i] == quote:
                        quote = None
                    i += 1
            elif pair == '//':
                break
            elif pair == '/*':
                in_block = True
                i += 2
            else:
                # Verilog apostrophes denote literals, not C character strings.
                if line[i] == '"' or (line[i] == "'" and Path(p).suffix not in {'.v', '.vh', '.sv', '.svh'}):
                    quote = line[i]
                out.append(line[i])
                i += 1
        flags.append(bool(''.join(out).strip()))
    return flags


def blame_records(text):
    result = []
    record = {}
    for line in text.splitlines():
        m = re.match(r'^([0-9a-f]{40}) (\d+) (\d+)(?: \d+)?$', line)
        if m:
            record = {'commit': m[1], 'original_line': int(m[2]), 'line': int(m[3])}
        elif line.startswith('author '):
            record['author'] = line[7:]
        elif line.startswith('author-mail '):
            record['email'] = line[12:].strip('<>')
        elif line.startswith('filename '):
            record['original_path'] = line[9:]
        elif line.startswith('\t'):
            result.append(record.copy())
    return result


def revision_totals(repo, revision):
    totals, files = collections.Counter(), collections.Counter()
    for p in git(repo, 'ls-tree', '-r', '--name-only', revision).splitlines():
        if is_source(p):
            s = git(repo, 'show', revision + ':' + p)
            b = bucket(p, s)
            totals[b] += sum(sloc_mask(p, s))
            files[b] += 1
    return {'sloc': dict(totals), 'files': dict(files)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--repo', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--revision', default='HEAD')
    ap.add_argument('--upstream', default='upstream/main')
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    head = git(args.repo, 'rev-parse', args.revision).strip()
    upstream = git(args.repo, 'rev-parse', args.upstream).strip()
    base_commits = set(git(args.repo, 'rev-list', BASE).splitlines())
    upstream_commits = set(git(args.repo, 'rev-list', upstream).splitlines())
    port_commits = {x.split()[0] for x in git(args.repo, 'log', head, '--format=%H %s', '--grep=port: HarpMudd upstream').splitlines()}
    paths = git(args.repo, 'ls-tree', '-r', '--name-only', head).splitlines()
    base_paths = set(git(args.repo, 'ls-tree', '-r', '--name-only', BASE).splitlines())
    upstream_paths = set(git(args.repo, 'ls-tree', '-r', '--name-only', upstream).splitlines())

    def compare(p, s, revision, members):
        if p not in members:
            return {'status': 'absent', 'sloc': 0, 'matching_sloc': 0}
        old = git(args.repo, 'show', revision + ':' + p)
        oldmask = sloc_mask(p, old)
        oldlines, newlines = old.splitlines(), s.splitlines()
        newmask = sloc_mask(p, s)
        matched = sum(newmask[j] for block in difflib.SequenceMatcher(None, oldlines, newlines, autojunk=False).get_matching_blocks() for j in range(block.b, block.b + block.size))
        return {'status': 'identical' if old == s else 'modified', 'sloc': sum(oldmask), 'matching_sloc': matched}

    def process(p):
        s = git(args.repo, 'show', head + ':' + p)
        mask = sloc_mask(p, s)
        records = blame_records(git(args.repo, 'blame', '--line-porcelain', '-w', '-M', '-C', '-C', head, '--', p))
        assert len(records) == len(s.splitlines()), (p, len(records), len(s.splitlines()))
        counts = collections.Counter()
        authors = collections.Counter()
        ranges = []
        for rec, include in zip(records, mask):
            if not include:
                continue
            c = rec['commit']
            name = rec.get('author', '?')
            authors[name] += 1
            origin = 'fork_baseline' if c in base_commits else ('later_upstream' if c in upstream_commits else ('declared_upstream_port' if c in port_commits else 'tau_lineage'))
            counts[origin] += 1
            if name.casefold() == 'harpmudd':
                counts['harpmudd_blame'] += 1
            key = (origin, name, c, rec.get('original_path'))
            if ranges and ranges[-1]['key'] == key and ranges[-1]['end'] + 1 == rec['line'] and ranges[-1]['original_line'] + ranges[-1]['end'] - ranges[-1]['start'] + 1 == rec['original_line']:
                ranges[-1]['end'] = rec['line']
            else:
                ranges.append({'key': key, 'start': rec['line'], 'end': rec['line'], 'original_line': rec['original_line']})
        for r in ranges:
            origin, author, commit, original_path = r.pop('key')
            r.update(origin=origin, author=author, commit=commit, original_path=original_path)
        b = compare(p, s, BASE, base_paths)
        u = compare(p, s, upstream, upstream_paths)
        row = {'path': p, 'bucket': bucket(p, s), 'physical_lines': len(s.splitlines()), 'nonblank_lines': sum(bool(x.strip()) for x in s.splitlines()), 'sloc': sum(mask), 'harpmudd_blame': counts['harpmudd_blame'], 'fork_baseline': counts['fork_baseline'], 'later_upstream': counts['later_upstream'], 'declared_upstream_port': counts['declared_upstream_port'], 'tau_lineage': counts['tau_lineage'], 'base_status': b['status'], 'base_sloc': b['sloc'], 'base_matching_sloc': b['matching_sloc'], 'upstream_status': u['status'], 'upstream_sloc': u['sloc'], 'upstream_matching_sloc': u['matching_sloc'], 'sha256': hashlib.sha256(s.encode()).hexdigest(), 'authors': dict(authors)}
        return row, ranges

    sources = [p for p in paths if is_source(p)]
    rows, ranges = [], {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        for i, (row, rs) in enumerate(pool.map(process, sources), 1):
            rows.append(row)
            ranges[row['path']] = rs
            if i % 50 == 0:
                print(f'{i}/{len(sources)} source files measured', flush=True)
    rows.sort(key=lambda x: x['path'])
    fields = [x for x in rows[0] if x != 'authors']
    with (args.out / 'files.csv').open('w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows({k: v for k, v in x.items() if k != 'authors'} for x in rows)
    totals = {}
    metrics = ['physical_lines', 'nonblank_lines', 'sloc', 'harpmudd_blame', 'fork_baseline', 'later_upstream', 'declared_upstream_port', 'tau_lineage', 'base_matching_sloc', 'upstream_matching_sloc']
    for group in sorted({x['bucket'] for x in rows}):
        subset = [x for x in rows if x['bucket'] == group]
        totals[group] = {'files': len(subset), **{k: sum(x[k] for x in subset) for k in metrics}}
    authors = collections.Counter()
    for x in rows:
        if x['bucket'] in {'firmware', 'rtl', 'tooling', 'test'}:
            authors.update(x['authors'])
    # Deduplicate moved/copied occurrences before discussing original-source survival.
    retained_original = set()
    for row in rows:
        if row['bucket'] not in {'firmware', 'rtl'}:
            continue
        for r in ranges[row['path']]:
            if r['origin'] == 'fork_baseline':
                for i in range(r['end'] - r['start'] + 1):
                    retained_original.add((r['commit'], r['original_path'], r['original_line'] + i))
    original_keys = set()
    for p in sorted(base_paths):
        if not is_source(p):
            continue
        s = git(args.repo, 'show', BASE + ':' + p)
        if bucket(p, s) not in {'firmware', 'rtl'}:
            continue
        records = blame_records(git(args.repo, 'blame', '--line-porcelain', '-w', '-M', '-C', '-C', BASE, '--', p))
        for rec, include in zip(records, sloc_mask(p, s)):
            if include:
                original_keys.add((rec['commit'], rec['original_path'], rec['original_line']))
    survival = {'fork_production_unique_origins': len(original_keys), 'retained_production_unique_origins': len(retained_original & original_keys), 'current_production_fork_origin_occurrences': sum(x['fork_baseline'] for x in rows if x['bucket'] in {'firmware', 'rtl'}), 'definition': 'unique (origin commit, original filename, original line) identities in fork/current maintained firmware+RTL; copies counted once'}
    inventory = [{'path': p, 'source': is_source(p)} for p in paths]
    deleted = sorted(p for p in base_paths - set(paths) if is_source(p))
    trailers = git(args.repo, 'log', head, '--format=%H%x09%an%x09%(trailers:key=Co-authored-by,valueonly,separator=%x7C)')
    (args.out / 'coauthors.tsv').write_text(trailers)
    result = {'tau_revision': head, 'fork_revision': BASE, 'upstream_revision': upstream, 'blame_flags': ['-w', '-M', '-C', '-C'], 'sloc_definition': 'nonblank non-comment physical source lines; Python docstrings count as source; build scripts use leading hash comments only', 'source_extensions': sorted(EXTS), 'source_files': len(rows), 'tracked_files': len(paths), 'totals_by_bucket': totals, 'firstparty_authors_sloc': dict(authors), 'original_production_survival': survival, 'deleted_fork_source_paths': deleted, 'files': rows, 'inventory': inventory}
    (args.out / 'summary.json').write_text(json.dumps(result, indent=2) + '\n')
    (args.out / 'line-origins.json').write_text(json.dumps(ranges, indent=2) + '\n')
    (args.out / 'comparison-totals.json').write_text(json.dumps({r: revision_totals(args.repo, r) for r in [BASE, upstream]}, indent=2) + '\n')
    print(json.dumps({'tau_revision': head, 'upstream_revision': upstream, 'totals': totals, 'authors': dict(authors), 'survival': survival, 'deleted': deleted}, indent=2), flush=True)


if __name__ == '__main__':
    main()
