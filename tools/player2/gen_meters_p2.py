#!/usr/bin/env python3
"""Generates the Player 2 meter tables from the manifests (meters/<key>/meter.json), nothing else is maintained by hand:
  fw2/generated/meter_presets.h    parameter ids, presets and Configure-page descriptors of Winamp Bars, Winamp Scope, Chladni, Master VU (and the descriptors of Layered Wave)
  fw2/generated/lw_presets.h       Layered Wave's parameter ids and its 16 presets
  fw2/generated/meter_registry.h   the registry: the meter list in table order (the manifest's p2.slot), manifest ids, preset counts, compose flags
A meter's manifest carries "p2": {"slot": N, "tag": "BARS", "compose": false}. Slots are append-only once shipped (the saved meter is the table index).
Usage: gen_meters_p2.py [--check]"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
HIDE_EXACT = {"info"}                                                    # not drawn in Player 2 (the VU info overlay is not ported)
def is_colour(k, p): return p["type"] == "u16" and (k.startswith("custom_") or k in ("color_green", "color_yellow", "color_red"))       # raw RGB565 values: the Configure page's colour picker
def hidden(k, p):
    if k in HIDE_EXACT: return 1
    return 0                                                         # the experimental group and the colours are shown (type 3 = colour picker)
def descriptors(tag, d):
    keys = [p["key"] for p in d["params"]]; res = []
    for i, p in enumerate(d["params"]):
        k = p["key"]; n = 0; vals = "0"
        if p["type"] == "enum":
            vals = f"mpl_{tag.lower()}_{k}"; res.append(f"static const char *const {vals}[] = {{ " + ", ".join('"%s"' % v.replace("_", " ") for v in p["values"]) + " };"); n = len(p["values"])
        w = p.get("when"); wi, wv = 255, 0
        if isinstance(w, dict) and len(w) >= 1:
            wk, wval = next(iter(w.items()))
            if wk in keys and isinstance(wval, int): wi, wv = keys.index(wk), wval
        ty = 3 if is_colour(k, p) else {"enum": 1, "bool": 2}.get(p["type"], 0); lo, hi, st = (0, n - 1, 1) if ty == 1 else (0, 1, 1) if ty == 2 else (0, 65535, 1) if ty == 3 else (p["min"], p["max"], p["step"])
        res.append((i, '{ "%s", %d, %d, %d, %d, %d, %d, %s, %d, %d },' % (p["label"].upper(), ty, hidden(k, p), lo, hi, st, n, vals, wi, wv)))
    lines = [x for x in res if isinstance(x, str)]
    rows = [x[1] for x in res if not isinstance(x, str)]
    return lines + [f"static const mpd_t mpd_{tag.lower()}[{len(rows)}] = {{"] + ["    " + r for r in rows] + ["};", f"#define MPD_{tag}_N {len(rows)}u"]

def load():
    man = {}
    for p in sorted((ROOT / "meters").glob("*/meter.json")):
        d = json.loads(p.read_text())
        if "p2" in d: man[d["key"]] = d
    slots = sorted(d["p2"]["slot"] for d in man.values())
    assert slots == list(range(len(man))), f"the p2 slots must be exactly 0..{len(man) - 1}: {slots}"
    return man
MAN = load()
ORDER = sorted(MAN.values(), key=lambda d: d["p2"]["slot"])             # the table order = the saved meter index
PLAIN = [(d["key"], d["p2"]["tag"]) for d in ORDER if d["key"] != "layered_wave"]      # meters whose ids and presets go into meter_presets.h (Layered Wave has its own header and names)
out = ["/* generated by tools/player2/gen_meters_p2.py from the meters directory (each meter.json): do not edit */", "#ifndef P2_METER_PRESETS_H", "#define P2_METER_PRESETS_H", "#include <stdint.h>",
       "#ifndef P2_MPD_T", "#define P2_MPD_T", "/* a parameter the Configure page can edit: type 0 number, 1 choice, 2 on/off, 3 colour (a raw RGB565 value, edited by the picker); shown only when the parameter `when_idx` has the value `when_val` (255 = always) */", "typedef struct { const char *label; uint8_t type, hidden; uint16_t min, max, step; uint8_t nval; const char *const *vals; uint8_t when_idx; uint16_t when_val; } mpd_t;", "#endif"]
for key, tag in PLAIN:
    d = MAN[key]
    keys = [p["key"] for p in d["params"]]
    out.append("enum { " + ", ".join(f"MPP_{tag}_{k.upper()}" for k in keys) + f", MPP_{tag}_N }};")
    out.append(f"#define MPP_{tag}_PRESETS {len(d['presets'])}u")
    out.append(f"static const char *const mpp_{tag.lower()}_name[MPP_{tag}_PRESETS] = {{ " + ", ".join('"%s"' % p["name"] for p in d["presets"]) + " };")
    out.append(f"static const uint16_t mpp_{tag.lower()}[MPP_{tag}_PRESETS][MPP_{tag}_N] = {{")
    for p in d["presets"]:
        out.append("    { " + ", ".join(str(p["values"][k]) for k in keys) + f" }},   /* {p['name']} */")
    out.append("};")
    out += descriptors(tag, d)
lw = MAN["layered_wave"]
out += descriptors("LW", lw)
out += ["#endif", ""]
presets_text = "\n".join(out)

lkeys = [p["key"] for p in lw["params"]]
lout = ["/* generated by tools/player2/gen_meters_p2.py from meters/layered_wave/meter.json: do not edit */",
        "#ifndef P2_LW_PRESETS_H", "#define P2_LW_PRESETS_H", "#include <stdint.h>",
        "enum { " + ", ".join("MP_LAYERED_WAVE_" + k.upper() for k in lkeys) + ", MP_LAYERED_WAVE_N };", f"#define LW_PRESET_N {len(lw['presets'])}u",
        "static const char *const lw_preset_name[LW_PRESET_N] = { " + ", ".join('"%s"' % p["name"] for p in lw["presets"]) + " };",
        "static const uint16_t lw_preset[LW_PRESET_N][MP_LAYERED_WAVE_N] = {"]
for p in lw["presets"]: lout.append("    { " + ", ".join(str(p["values"][k]) for k in lkeys) + " },   /* " + p["name"] + " */")
lout += ["};", "#endif", ""]
lw_text = "\n".join(lout)

rout = ["/* generated by tools/player2/gen_meters_p2.py from the manifests (meters/<key>/meter.json, the p2 block): do not edit. The meter table of fw2/ui/meters.c, its externs and the manifest ids come from here. */",
        "#ifndef P2_METER_REGISTRY_H", "#define P2_METER_REGISTRY_H", "#include <stdint.h>", f"#define METER_N {len(ORDER)}u",
        "/* X(key, NAME, manifest_id, tag_lower, TAG, presets, compose), in table order (the saved meter is the table index: slots never move, new meters append) */", "#define METER_LIST(X) \\"]
for n, d in enumerate(ORDER):
    tag = d["p2"]["tag"]
    rout.append('    X(%s, "%s", %d, %s, %s, %d, %d)%s' % (d["key"], d["p2"].get("label", d["name"]), d["index"], tag.lower(), tag, len(d["presets"]), 1 if d["p2"].get("compose") else 0, " \\" if n + 1 < len(ORDER) else ""))
rout.append("static const uint8_t meter_manifest_id[METER_N] = { " + ", ".join(str(d["index"]) for d in ORDER) + " };      /* the id of each table entry in tau-assets.bin METR and the reports */")
rout += ["#endif", ""]
reg_text = "\n".join(rout)

OUT = {"fw2/generated/meter_presets.h": presets_text, "fw2/generated/lw_presets.h": lw_text, "fw2/generated/meter_registry.h": reg_text}
if "--check" in sys.argv:
    bad = [n for n, t in OUT.items() if not ((ROOT / n).exists() and (ROOT / n).read_text() == t)]
    for n in OUT: print(("STALE " if n in bad else "up to date ") + n)
    sys.exit(1 if bad else 0)
for n, t in OUT.items(): (ROOT / n).write_text(t)
