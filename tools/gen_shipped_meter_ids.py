#!/usr/bin/env python3
"""Generate fw2/cores/shipped_meter_ids.h from the manifests (meters/<key>/meter.json): the manifests are the single source of each shipped meter's `id` (its id_hash), `params_rev` and manifest `index`
(P2.6: before this the header held hand-written placeholders). Order = the manifests' p2 slot, the order of the TOC the build composes.

  python3 tools/gen_shipped_meter_ids.py            write the header
  python3 tools/gen_shipped_meter_ids.py --check    exit 1 (and say how to fix it) when the header differs from what the manifests give

`tau_min` is not in the header (the firmware does not use it for the persisted tunings' keys): it lives in the manifest and reaches the TOC row through tools/meter_package.py and tools/meter_bin.py.
sim/test_meter_package.py fails when the committed header and the manifests differ."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "fw2/cores/shipped_meter_ids.h"

TEMPLATE = """/* fw2/cores/shipped_meter_ids.h -- GENERATED by tools/gen_shipped_meter_ids.py from meters/<key>/meter.json: do not edit by hand (sim/test_meter_package.py fails when it differs from the manifests).
 * THE ONE PLACE that maps the table index of the seven shipped meters (the index that layout 0 and layout 1 of the persisted settings stored) to the identity a meter has in the external-meters design
 * (docs/features/meters/EXTERNAL_METERS_SPEC.md section 5): its `id_hash` (the first 32 bits of the 128-bit id) and `params_rev` (the low 4 bits are part of a saved tuning's key).
 *
 * The id_hash values are the FINAL ids of P2.0 (the first 8 hex digits of `id` in the manifest). `params_rev` is the manifest's own field since P2.6 (the same number goes into the TOC row of the shipped bin; one is above 15 on
 * purpose: only the low 4 bits are part of a key). Line format X(index, id_hash, params_rev): tools/persist_layout.py reads it by regular expression. Order = the manifests' p2 slot (tools/player2/gen_meters_p2.py): %(order)s. */
#ifndef SHIPPED_METER_IDS_H
#define SHIPPED_METER_IDS_H
#include <stdint.h>
#define SHIPPED_METERS_N %(n)du
#define SHIPPED_METER_LIST(X) \\
%(rows)s
/* The manifest index (meters/<key>/meter.json "index") of each shipped meter, in the same order: the id the METR section of tau-assets.bin is keyed by (12 ... 18) and the folder name of tau-presets/ on cards made before external
 * meters (the firmware still reads those folders when the hash folder is absent). sim/test_p2_meter_window.py checks this list against the manifests. */
#define SHIPPED_MID_LIST(X) %(mids)s
#define SHIPPED_MID_X(m) m,
#define SHIPPED_HASH_X(i, h, r) h,
#define SHIPPED_REV_X(i, h, r) r,
static const uint32_t shipped_meter_hash[SHIPPED_METERS_N] = { SHIPPED_METER_LIST(SHIPPED_HASH_X) };   /* the whole 32-bit id_hash */
static const uint8_t shipped_meter_rev[SHIPPED_METERS_N] = { SHIPPED_METER_LIST(SHIPPED_REV_X) };      /* params_rev */
__attribute__((unused)) static const uint8_t shipped_meter_mid[SHIPPED_METERS_N] = { SHIPPED_MID_LIST(SHIPPED_MID_X) };      /* manifest index */
#endif
"""


def shipped(meters_dir=ROOT / "meters"):
    """[manifest dict] of the shipped meters (a p2 block), in p2 slot order"""
    ms = [json.loads(p.read_text()) for p in sorted(Path(meters_dir).glob("*/meter.json"))]
    return sorted((m for m in ms if "p2" in m), key=lambda m: m["p2"]["slot"])


def render(meters_dir=ROOT / "meters"):
    ms = shipped(meters_dir)
    for m in ms:
        assert 0 <= m["params_rev"] <= 255, f"{m['key']}: params_rev {m['params_rev']} does not fit the header's uint8_t"
    w = max(len(m["key"]) for m in ms)
    rows = " \\\n".join("    X(%d, 0x%su, %du)%s /* %s */" % (i, m["id"][:8].upper(), m["params_rev"], " " * (1 if m["params_rev"] < 10 else 0), m["key"].ljust(w)) for i, m in enumerate(ms))
    return TEMPLATE % dict(order=", ".join(m["key"] for m in ms), n=len(ms), rows=rows, mids=" ".join("X(%d)" % m["index"] for m in ms))


def main(argv):
    text = render()
    if "--check" in argv:
        if HEADER.read_text() != text:
            print("fw2/cores/shipped_meter_ids.h differs from the manifests: run python3 tools/gen_shipped_meter_ids.py"); return 1
        print("shipped_meter_ids.h matches the manifests"); return 0
    HEADER.write_text(text); print("wrote", HEADER.relative_to(ROOT)); return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
