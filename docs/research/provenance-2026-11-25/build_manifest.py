#!/usr/bin/env python3
"""Build harpmudd_manifest.csv from files.csv (measure.py, copy-aware blame) + readers.json + fw_blockers.json.
Run from the repo root after measure.py, readers.py, fw_blockers.py. The per-file verdict rules and the
hand-written notes (replacement, proof, blocker) are in this file so the manifest is reproducible.

Verdict rules (a % is HarpMudd-origin lines / source lines by copy-aware blame; NOT creative ownership):
  THIRD-PARTY     vendored or generated code whose author is not HarpMudd (blame only shows HarpMudd imported it)
  ORIGINAL-HARPMUDD  >= 70 % and not third party
  MIXED           15 % to < 70 %
  TAU-OWN         < 15 % (a few inherited lines or boilerplate; clean-room or Tau-written)
"""
import csv, json, os, re, subprocess
OUT = 'docs/research/provenance-2026-11-25'
rows = {r['path']: r for r in csv.DictReader(open(f'{OUT}/files.csv'))}
readers = json.load(open(f'{OUT}/readers.json'))
fwb = json.load(open(f'{OUT}/fw_blockers.json'))
tracked = set(subprocess.run(['git', 'ls-files'], capture_output=True, text=True).stdout.split('\n'))
MOVED = {p for p in os.popen('find legacy-harpmudd -type f ! -name README.md').read().split('\n') if p}
moved_orig = {p[len('legacy-harpmudd/'):] for p in MOVED}
fw2build = open('fw2/build.sh').read()
qsf = open('src/fpga/ap_core.qsf').read() + ''.join(open(f).read() for f in tracked if f.startswith('src/fpga/') and f.endswith(('.qip', '.txt')))
game = open('src/fpga/core/core_game.vh').read()

TP = {  # path prefix -> (whose, licence)
 'third_party/libhelix-mp3': ('RealNetworks / Helix Community (Tau: small macro-gated edits in 6 files)', 'RealNetworks Public Source License 1.0 (RPSL)'),
 'third_party/picojpeg': ('Rich Geldreich, changes by Chris Phoenix', 'public domain (per file header)'),
 'src/fpga/rtl/VexRiscv_Full.v': ('Charles Papon / SpinalHDL (generated)', 'MIT as stated by the project; no header in the file'),
 'src/fpga/apf/': ('Analogue Inc (openFPGA APF framework)', 'Analogue APF licence / Pocket EULA terms in the file headers'),
 'src/fpga/core/core_bridge_cmd.v': ('Analogue Inc (openFPGA APF bridge)', 'Analogue APF licence in the header'),
 'src/fpga/core/mf_pllbase': ('Intel/Altera Quartus-generated PLL', 'Intel IP, tool generated'),
 'src/fpga/core/data_loader.sv': ('Adam Gastineau (agg23), from opengateware', 'MIT'),
 'src/fpga/core/sound_i2s.v': ('Adam Gastineau (agg23)', 'MIT'),
 'src/fpga/core/sync_fifo.v': ('Adam Gastineau (agg23)', 'MIT'),
 'sim/legacy_sdram/tau_sdram_ctrl.sv': ('Adam Gastineau (agg23) lineage, via HarpMudd', 'MIT (sim/legacy_sdram/sdram_LICENSE)'),
 'src/fpga/core/font_rom.v': ('generated by tools/gen_font_rom.py from the Inter typeface (Rasmus Andersson)', 'SIL OFL 1.1 (font); generator is HarpMudd-lineage'),
 'src/fpga/core/font_ram.v': ('generated by tools/gen_font_atlases.py from Tamzen / Space Grotesk / Inter (Tau generator)', 'OFL 1.1 / Tamzen licence; blame match is copy-detection on generated hex data: VERIFY'),
 'sim/common/test_mp3': ('lieff / minimp3 CC0 test vectors', 'CC0'),
}
def third(p):
    for k, v in TP.items():
        if p.startswith(k): return v
    return None

# hand-written replacement / proof / note, keyed by path or prefix (first match wins)
NOTE = [
 ('fw/player.c', ('fw2/ (Player 2, shipped since v0.6.0); 20 inherited lines remain in fw2', 'Pocket: Player 2 is the shipped player; host tests of fw2', 'blocked: 6 live checks read it (gen_themes --check, check_splash_asset/test_splash_asset, test_meter_core, tools/meters/preview/build.py, gen_meters --check, tools/player2/globals_map.py); smallest change: point those at fw2 equivalents (see HARPMUDD_DISCONTINUATION_STATUS_2026-10-18.md section "Next")')),
 ('fw/art.inc', ('fw2/art/art.c', 'sim/test_art_decode.py + Pocket (art shown)', 'blocked: sim/test_art_decode.py, sim/gen_art_fixtures.py, tools/host/art_decode_harness.c, tools/library_check.py read it; re-point to fw2/art')),
 ('fw/playlist.inc', ('fw2/stream/ + fw2/transport/browser.c', 'host harness + Pocket', 'blocked: tools/library_check.py (Makefile), sim/test_sdram_map_overlap.py read it')),
 ('fw/settings.inc', ('fw2/settings/settings.c', 'migration confirmed on Pocket (B-847)', 'blocked: fw2/cores/settings_core.h and settings.c name it in comments; tools/player2/globals_map.py reads it; re-point')),
 ('fw/build.sh', ('fw2/build.sh', 'fw2 build + Pocket', 'blocked: Makefile, fw2/build.sh (comments), gen_diag_features.py --check, check_heap_gap, make_release legacy path read it')),
 ('fw/flac.h', ('fw2/decode flac2 (clean FLAC decoder, S9)', 'sim/test_p2_flac2_*.py, Pocket', 'blocked: tools/host/seek|skip|spectrum_harness.c and tools/lab/flacperf include it')),
 ('fw/font_metrics.h', ('generated by tools/gen_font_rom.py', 'sim/test_font_fit.py', 'blocked: sim/test_font_fit.py, tools/gen_font_rom.py, tools/ui_snapshot_renderer.py')),
 ('src/fpga/core/tau_talos.sv', ('NONE yet: row-job engine rewrite parked by D-T12 (no measured need); the old engine text is still the shipped engine', 'would need differential fuzz vs sim/oracle/tau_talos1_oracle.sv + Pocket (D-T01)', 'OWNER DECISION: D-T01 lists the engine as a step; D-T12 parked it')),
 ('src/fpga/core/tau_soc.v', ('NONE: SoC/MMIO integration (renamed from mp3_soc, D-T02); inherited CPU/MMIO basis', 'needs a contract + tb + fit + Pocket', 'not started; not in D-T01 explicitly (only the rename)')),
 ('src/fpga/core/core_game.vh', ('NONE: integration glue (clocks, bridge, wiring); partly framework-derived', 'fit + Pocket', 'not started; wiring is inherently shared with the APF shell')),
 ('src/fpga/core/core_top.v', ('NONE: the frozen APF shell top (Analogue template via HarpMudd)', 'n/a', 'framework scaffold; replace only by re-deriving from Analogue template; OWNER/LEGAL view')),
 ('src/fpga/core/tgt_cmd.v', ('NONE', 'tb_tgt_cmd + Pocket', 'target-command CDC; small (76 lines); candidate for clean-room contract')),
 ('src/fpga/core/pcm_fifo.v', ('NONE', 'tb_pcm_fifo + tb_pcm_decay + Pocket', 'audio FIFO (63 lines); candidate for clean-room contract')),
 ('src/fpga/core/tau_gfx.sv', ('Tau-own wrapper; 19 inherited lines (boilerplate/ports of the former mp3_fb top)', 'tb_tau_gfx_diff', 'trivial: rewrite the 19 lines when the engine is replaced')),
 ('src/fpga/core/tau_scanout.sv', ('DONE clean-room (D-T07)', 'tb_tau_scanout_diff, 12 mutants, Pocket DEV 198', 'none')),
 ('src/fpga/core/tau_sdram_', ('DONE: new PHY + scheduler (D-T09/D-T13)', 'sim chip model, A-094, soak 46 passes on Pocket (DEV 200)', 'minor inherited lines only')),
 ('sim/oracle/tau_scanout1_oracle.sv', ('replaced by src/fpga/core/tau_scanout.sv (Pocket-confirmed DEV 198)', 'the scanout replacement is Pocket-confirmed; this file is simulation-only, never synthesised: it is the black-box reference of tb_tau_scanout_diff (make test-rtl-scanout-diff)', 'meets D-T01 deletion gate; delete together with the diff bench/Makefile target after OWNER approval (planned in removal.patch)')),
 ('sim/oracle/tau_talos1_oracle.sv', ('NONE: this is the pre-split engine reference; the engine itself is unreplaced', 'differential bench tb_tau_gfx_diff needs it', 'keep until the engine is replaced and Pocket-confirmed')),
 ('sim/legacy_sdram/', ('replaced by tau_sdram_phy + sched_a (Pocket DEV 200)', 'Pocket-confirmed (D-T13); kept only as the old-behaviour model for two benches', 'blocked: sim/sdram_baseline/run_baseline.sh, sim/sdram_sched_a/run_gfx.sh, sim/tb_mp3_fb.v, sim/test_check_qsf_files.py name it; meets D-T13 gate; delete after OWNER approval together with those benches')),
 ('sim/tb_mp3_fb.v', ('tests the pre-split engine through the oracle', 'Makefile test-rtl-* targets', 'blocked: Makefile, tb_blit_scene, tb_font_ram, tb_helios_dbuf include it')),
 ('tools/rv32sim.py', ('none (an RV32 host simulator; the SDK has its own rv32run.c)', 'used by 44 files', 'blocked: fw2/cores harness tests, sim tests run it; replace with sdk/sdk/runner/rv32run.c only after parity proof')),
 ('tools/gen_eq_coeffs.py', ('Halcyon (own design) replaced the engine; script kept for tools/lab models', 'sim/test_halcyon_generator.py', 'blocked: tools/lab/halcyon_model.py, eq_cramping, eq_coeff_precision import it')),
 ('tools/gen_font_rom.py', ('tools/gen_font_atlases.py (Tau, writes font_ram.v and .tfnt)', 'sim/test_font_ram.py', 'blocked: still generates font_rom.v / font_metrics.h read by tb_*, fw/player.c, test_font_fit')),
 ('tools/gen_text_gamma.py', ('keeps the bit-exact text gamma table the engine uses', 'sim/test_blit_reference.py', 'blocked: generates the table included by tau_talos.sv, tau_gfx.sv and the oracle')),
 ('tools/library_check.py', ('none', 'Makefile target', 'blocked: Makefile, tools/sync_media.py')),
 ('package.py', ('tools/make_release.py --player2 is the release path; package.py still builds the DEV card package', 'make package, check_tau_package', 'blocked: Makefile, SDK vendors meter_package.py from it')),
 ('tools/flac_', ('fw2 flac2 + sim/flac2_enc.py', 'n/a', 'see readers')),
]
def note(p):
    for k, v in NOTE:
        if p.startswith(k) or p == k: return v
    return None

sel = []
for p, r in rows.items():
    h = int(r['harpmudd_blame']); s = max(int(r['sloc']), 1)
    if h >= 10 or h >= .25 * s: sel.append(p)

def shipped(p):
    b = os.path.basename(p)
    if p.startswith('third_party/libhelix-mp3/'):
        return 'yes' if (b in fw2build or p.split('/')[-1].replace('.c', '') in fw2build) and '/testwrap/' not in p and '/arm/' not in p else ('yes (headers)' if p.endswith('.h') and '/testwrap/' not in p else 'no')
    if p.startswith('third_party/picojpeg'): return 'yes' if 'picojpeg' in fw2build or True else 'no'
    if p.startswith('fw/'): return 'yes (header read by fw2)' if p in fwb['fw2_included'] else 'no'
    if p.startswith('src/fpga/'):
        return 'yes' if (b in qsf or b in game or p.endswith('.sdc') or b.endswith('.vh')) else 'verify'
    if p.startswith('fw2/') or p.startswith('sdk/'): return 'yes' if p.startswith('fw2/') else 'no (SDK vendors a copy)'
    if p == 'package.py': return 'builds the release (tool)'
    return 'no'

out = []
for p in sorted(sel, key=lambda x: -int(rows[x]['harpmudd_blame'])):
    r = rows[p]; h = int(r['harpmudd_blame']); s = int(r['sloc']); pct = 100 * h / max(s, 1)
    tp = third(p)
    if tp: verdict = 'THIRD-PARTY'
    elif pct >= 70: verdict = 'ORIGINAL-HARPMUDD'
    elif pct >= 15: verdict = 'MIXED'
    else: verdict = 'TAU-OWN'
    n = note(p)
    rd = readers.get(p, [])
    if p in fwb['not_included']: rd = fwb['not_included'][p]
    live = [x for x in rd if not x.startswith(('docs/', 'legacy-harpmudd/'))]
    if p in moved_orig: status = 'MOVED to legacy-harpmudd/ (no live reader)'
    elif p.startswith('legacy-harpmudd/'): status = 'moved'
    elif verdict == 'THIRD-PARTY': status = 'KEEP (third party; attribution, not removal)'
    elif n and n[2].startswith('blocked'): status = 'BLOCKED'
    elif n and n[2].startswith('meets'): status = 'READY after owner approval'
    elif live and verdict in ('ORIGINAL-HARPMUDD', 'MIXED') and not p.startswith('fw/'): status = 'BLOCKED'
    elif verdict == 'TAU-OWN': status = 'KEEP (few inherited lines)'
    else: status = 'BLOCKED' if live else 'candidate'
    repl = n[0] if n else ('none' if verdict != 'THIRD-PARTY' else f'n/a ({tp[0]}; {tp[1]})')
    proof = n[1] if n else ''
    blocker = n[2] if n else ('; '.join(live[:6]) + (f' (+{len(live)-6} more)' if len(live) > 6 else '') if live else 'none found')
    if tp and not n: blocker = f'{tp[0]} | licence: {tp[1]}'
    out.append([p, s, h, f'{pct:.0f}', verdict, shipped(p), status, blocker, repl, proof])
# the moved files had their rows measured at the old path: report them with the new location
for o in out:
    if o[0] in moved_orig: o[0] = 'legacy-harpmudd/' + o[0]; o[6] = 'MOVED from ' + o[0][len('legacy-harpmudd/'):] + ' (no live reader found)'
with open(f'{OUT}/harpmudd_manifest.csv', 'w', newline='') as f:
    w = csv.writer(f)
    w.writerow(['path', 'lines', 'harpmudd_lines', 'harpmudd_pct', 'verdict', 'shipped', 'status', 'blocker_or_readers_or_whose', 'replacement', 'proof_of_replacement'])
    w.writerows(out)
import collections
c = collections.Counter(o[4] for o in out); d = collections.defaultdict(int)
for o in out: d[o[4]] += o[2]
print(len(out), dict(c), dict(d))
print(collections.Counter(o[6].split(' ')[0] for o in out))
