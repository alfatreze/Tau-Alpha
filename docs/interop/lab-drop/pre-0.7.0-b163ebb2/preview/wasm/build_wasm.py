#!/usr/bin/env python3
"""Build the SOUND MAP twin of the meter lab: compile fw2/ui/meter_sound_map.c (the pack's own drawing source) through tools/meters/preview/wasm/sound_map_wasm.c to WebAssembly and write it, base64, with the
SHA-256 of every source it was built from, to tools/meters/preview/meters/sound_map_wasm.js (committed: the lab and Tau Omega need no toolchain).

  python3 tools/meters/preview/wasm/build_wasm.py            rebuild (needs Homebrew llvm + lld, see memory/reference-wasm-toolchain: clang --target=wasm32 and wasm-ld)
  python3 tools/meters/preview/wasm/build_wasm.py --check    exit 1 when a source changed since the committed module was built (no toolchain needed); with the toolchain it also rebuilds and compares the bytes
"""
import base64, hashlib, json, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
OUT = ROOT / "tools/meters/preview/meters/sound_map_wasm.js"
CLANG, WASM_LD = "/opt/homebrew/opt/llvm/bin/clang", "/opt/homebrew/opt/lld/bin/wasm-ld"
SOURCES = ["tools/meters/preview/wasm/sound_map_wasm.c", "fw2/ui/meter_sound_map.c", "fw2/ui/meter_grid.h", "fw2/ui/meter.h", "fw2/ui/theme.h", "fw2/gfx/gfx.h", "fw2/generated/meter_presets.h",
           "fw2/cores/audio_stats_core.h", "fw2/cores/cellgrid_core.h", "fw2/cores/histring_core.h", "fw2/cores/ramp_core.h"]


def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def compile_wasm(dst):
    cmd = [CLANG, "--target=wasm32", "-O2", "-nostdlib", "-ffreestanding", "-Wno-comment", "-fuse-ld=" + WASM_LD, "-Wl,--no-entry", "-Wl,--allow-undefined", "-Wl,--strip-all",
           "-I", str(ROOT / "fw2/ui"), "-I", str(ROOT / "fw2"), "-o", str(dst), str(HERE / "sound_map_wasm.c")]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode: sys.exit("wasm build failed:\n" + r.stderr)
    return Path(dst).read_bytes()


def committed():
    """(sources, wasm sha256, bytes) recorded in the committed module"""
    txt = OUT.read_text()
    meta = json.loads(txt[txt.index("/*META") + 6:txt.index("META*/")])
    b64 = txt[txt.index('b64: "') + 6:txt.index('"', txt.index('b64: "') + 6)]
    return meta, base64.b64decode(b64)


def main():
    if "--check" in sys.argv:
        meta, wasm = committed()
        stale = [s for s in SOURCES if meta["sources"].get(s) != sha(ROOT / s)]
        if hashlib.sha256(wasm).hexdigest() != meta["wasm_sha256"]: stale.append("the module's own checksum")
        if stale: print("STALE: rebuild with tools/meters/preview/wasm/build_wasm.py; changed:", ", ".join(stale)); return 1
        if Path(CLANG).exists() and Path(WASM_LD).exists():
            with tempfile.TemporaryDirectory() as td:
                fresh = compile_wasm(Path(td) / "sound_map.wasm")
            if fresh != wasm: print("the committed module differs from a fresh build (same sources: another toolchain version?)"); return 1
        print("sound_map_wasm.js is current (%d B)" % len(wasm)); return 0
    with tempfile.TemporaryDirectory() as td:
        wasm = compile_wasm(Path(td) / "sound_map.wasm")
    meta = {"about": "SOUND MAP compiled to WebAssembly from fw2/ui/meter_sound_map.c by tools/meters/preview/wasm/build_wasm.py", "wasm_sha256": hashlib.sha256(wasm).hexdigest(), "bytes": len(wasm),
            "sources": {s: sha(ROOT / s) for s in SOURCES}}
    OUT.write_text("/*META" + json.dumps(meta, indent=1) + "META*/\n/* GENERATED by tools/meters/preview/wasm/build_wasm.py: do not edit. */\n(function (root) {\n  const api = { b64: \"" + base64.b64encode(wasm).decode()
                   + "\", sha256: \"" + meta["wasm_sha256"] + "\" };\n  if (typeof module !== 'undefined') module.exports = api; else root.TauSoundMapWasm = api;\n})(typeof globalThis !== 'undefined' ? globalThis : window);\n")
    print("wrote %s (%d B of wasm)" % (OUT.relative_to(ROOT), len(wasm))); return 0


if __name__ == "__main__":
    sys.exit(main())
