#!/usr/bin/env python3
"""B-1172: a MONO MP3 goes through the MP3 window unit (pushed as both channels, left result taken) with the decoded output UNCHANGED.

sim/mp3_poly_mono_harness.c decodes REAL MP3 files with the REAL Helix (tools/helix_tree.py: pristine + tau.patch) twice: as today (TAU_POLY_FW=0, software PolyphaseMono /
PolyphaseStereo) and as Player 2 builds it (TAU_POLY_FW=1 TAU_POLY_REQUIRED=1, window = the golden model of the unit, real protocol). Every output sample must be identical, for
two or more mono files and for a stereo file (stereo behaviour must not have moved). Also checked: the unit really ran for every mono slot (not silently software), a missing / failing
unit gives counted silence for the rest of the mono track and nothing else, a second decoder instance clears the unit again. MUTATION cases rebuild the change with a deliberate
fault (wrong interleave stride, wrong duplicate-index drop, missing last-slot finish, destination of the pending slot, no clear for a new instance) and the unit with a wrong shift:
every one must make the comparison fail.
Media: the MP3 files in sim/fixtures-less form are generated by this test with lame/ffmpeg/say when present (sources are synthetic speech/noise, nothing is committed); if the encoders
are missing the test says so and SKIPS the file part (it never passes silently)."""
import os, shutil, subprocess, sys, tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gen_mp3_poly_rom as G
from helix_tree import helix_tree
H = helix_tree()
fails = 0
def check(name, ok, detail=""):
    global fails
    print(("ok   " if ok else "FAIL ") + name + ("" if ok else "  " + detail))
    if not ok: fails += 1

def make_media(md):
    """synthetic, deterministic enough sources: two mono speech files (TTS, different bitrates/modes), one loud mono noise file (clipping), one stereo file."""
    need = [shutil.which(x) for x in ("lame", "ffmpeg", "say")]
    if not all(need): return None
    def sh(*a): subprocess.run(a, check=True, capture_output=True, cwd=md)
    sh("say", "-v", "Samantha", "-o", "s1.aiff", "It was a bright cold day in April, and the clocks were striking thirteen. Winston Smith slipped quickly through the glass doors of Victory Mansions.")
    sh("say", "-v", "Daniel", "-r", "220", "-o", "s2.aiff", "The quick brown fox jumps over the lazy dog, then reads an audiobook about unusually loud thunderstorms and extremely quiet libraries.")
    sh("ffmpeg", "-loglevel", "error", "-y", "-i", "s1.aiff", "-ar", "44100", "-ac", "1", "s1.wav")
    sh("ffmpeg", "-loglevel", "error", "-y", "-i", "s2.aiff", "-ar", "44100", "-ac", "1", "s2.wav")
    sh("lame", "--silent", "-m", "m", "-b", "64", "s1.wav", "mono_speech64.mp3")
    sh("lame", "--silent", "-m", "m", "-V", "4", "s2.wav", "mono_speech_vbr.mp3")
    sh("ffmpeg", "-loglevel", "error", "-y", "-f", "lavfi", "-i", "anoisesrc=d=4:c=pink:seed=7:a=0.9,volume=1.5", "-ar", "44100", "-ac", "1", "loud.wav")
    sh("lame", "--silent", "-t", "-m", "m", "-b", "128", "loud.wav", "mono_loud128.mp3")     # -t: no Info frame (an Info frame is 36 silent slots and would flush any stale history)
    sh("ffmpeg", "-loglevel", "error", "-y", "-i", "s1.wav", "-af", "pan=stereo|c0=c0|c1=0.5*c0", "st.wav")
    sh("lame", "--silent", "-b", "128", "st.wav", "stereo128.mp3")
    return {"mono": [md / "mono_speech64.mp3", md / "mono_speech_vbr.mp3", md / "mono_loud128.mp3"], "stereo": [md / "stereo128.mp3"]}

taps, cf = G.build_map(), G.coefs()
with tempfile.TemporaryDirectory() as td:
    td = Path(td)
    src = td / "h"; shutil.copytree(H, src)
    shutil.copy(ROOT / "sim/helix_host/assembly.h", src / "real" / "assembly.h")
    shutil.copy(ROOT / "fw/mp3_poly_hw.h", td / "mp3_poly_hw.h")
    shutil.copy(ROOT / "sim/mp3_poly_model_core.h", td / "mp3_poly_model_core.h")
    (td / "tables.h").write_text(G.render_h(taps, cf))
    harness = ROOT / "sim/mp3_poly_mono_harness.c"
    def build(name, fw, req, subband=None, core=None):
        d = td / ("b_" + name); d.mkdir()
        shutil.copytree(src, d / "h"); hh = d / "h"
        shutil.copy(ROOT / "sim/helix_host/assembly.h", hh / "real" / "assembly.h")
        if subband is not None: (hh / "real/subband.c").write_text(subband)
        shutil.copy(harness, d / "harness.c"); shutil.copy(td / "tables.h", d / "tables.h"); shutil.copy(td / "mp3_poly_hw.h", d / "mp3_poly_hw.h")
        (d / "mp3_poly_model_core.h").write_text(core if core is not None else (td / "mp3_poly_model_core.h").read_text())
        srcs = [hh / "mp3dec.c", hh / "mp3tabs.c"] + [hh / "real" / (n + ".c") for n in "bitstream buffers dct32 dequant dqchan huffman hufftabs imdct polyphase scalfact stproc subband trigtabs".split()]
        exe = d / "dec"
        r = subprocess.run(["cc", "-std=gnu11", "-O1", "-w", "-DTABLES_H=\"tables.h\"", f"-DTAU_POLY_FW={fw}", f"-DTAU_POLY_REQUIRED={req}", "-I", str(d), "-I", str(hh / "pub"), "-I", str(hh / "real"),
                            "-o", str(exe), str(d / "harness.c")] + [str(s) for s in srcs], capture_output=True, text=True)
        if r.returncode: print(r.stderr); sys.exit(1)
        return exe
    def run(exe, mp3, *a):
        out = td / ("o_%s_%d.pcm" % (Path(exe).parent.name, abs(hash((str(mp3), a)))))
        r = subprocess.run([str(exe), str(mp3), str(out), *a], capture_output=True, text=True)
        f = r.stdout.split()
        d = dict(zip(f[::2], f[1::2])) if r.returncode == 0 and f else {}
        return (out.read_bytes() if out.exists() else b""), {k: int(v) for k, v in d.items()}, r.returncode, r.stderr.strip()
    md = td / "media"; md.mkdir()
    media = make_media(md)
    if media is None:
        print("SKIP  lame/ffmpeg/say not available: the real-file comparison did not run"); print("FAILED (1)"); sys.exit(1)
    sw, hw = build("sw", 0, 0), build("hw", 1, 1)
    refs = {}
    for kind, files in media.items():
        for f in files:
            pcm, info, rc, err = run(sw, f)
            refs[f] = (pcm, info)
            check(f"reference decode of {f.name} ({kind}): {info.get('FRAMES')} frames, {len(pcm) // 2} samples", rc == 0 and info.get("FRAMES", 0) > 20 and info.get("CH") == (1 if kind == "mono" else 2), err)
    for kind, files in media.items():
        for f in files:
            ref, rinfo = refs[f]
            pcm, info, rc, err = run(hw, f)
            check(f"{f.name}: output through the unit is identical sample for sample to the software window ({len(ref) // 2} samples)", rc == 0 and pcm == ref,
                  err or f"first difference at sample {next((i for i in range(0, min(len(pcm), len(ref)), 2) if pcm[i:i+2] != ref[i:i+2]), len(pcm)) // 2}")
            if kind == "mono":
                slots = rinfo["FRAMES"] * 36
                check(f"{f.name}: the unit really ran for all {slots} mono slots (not silently software) and nothing was silent", info.get("SLOTS") == slots and info.get("SILENT") == 0, str(info))
                check(f"{f.name}: one clear for the one decoder instance", info.get("CLEARS") == 1, str(info))
    # a second decoder instance on the same unit (the next track): the history must be cleared again
    refs2 = {}
    for f in media["mono"]:
        r2, i2, rc, err = run(sw, f, "-1", "0", "-1", "2"); refs2[f] = (r2, i2)
        h2, j2, rc2, err2 = run(hw, f, "-1", "0", "-1", "2")
        check(f"{f.name}: two decoder instances in a row on one unit: identical, 2 clears", rc2 == 0 and h2 == r2 and len(r2) == 2 * len(refs[f][0]) and j2.get("CLEARS") == 2, str(j2) + err2)
    # unit missing / failing: counted silence for the rest of the MONO track
    f = media["mono"][0]; ref, rinfo = refs[f]; slots = rinfo["FRAMES"] * 36
    pcm, info, rc, err = run(hw, f, "-1", "1")
    check("mono, unit absent: every slot silent and counted", rc == 0 and info.get("SILENT") == slots and set(pcm) <= {0} and len(pcm) == len(ref), str(info))
    for fs in (0, 5, 100, 700):
        pcm, info, rc, err = run(hw, f, str(fs))
        cut = fs * 32 * 2
        check(f"mono, unit fails to start slot {fs}: slots before exact, the rest silent, counted", rc == 0 and pcm[:cut] == ref[:cut] and set(pcm[cut:]) <= {0} and info.get("SILENT") == slots - fs, str(info))
    for fs in (0, 8, 100, 700):
        pcm, info, rc, err = run(hw, f, "-1", "0", str(fs))
        cut = fs * 32 * 2
        check(f"mono, slot {fs} never completes: slots before exact, that slot and the rest silent, counted", rc == 0 and pcm[:cut] == ref[:cut] and set(pcm[cut:]) <= {0} and info.get("SILENT") == slots - fs, str(info))
    # MUTATION: each deliberate fault in the change (or the unit) must be noticed by the comparison above
    sbc = (src / "real/subband.c").read_text()
    mono_at = sbc.index("		/* mono */")
    def mut(name, old, new, core=None):
        i = sbc.index(old, mono_at)
        exe = build("m_" + name, 1, 1, subband=sbc[:i] + new + sbc[i + len(old):], core=core)
        pcm, info, rc, err = run(exe, media["mono"][0])
        check(f"mutant killed: {name}", rc != 0 or pcm != refs[media["mono"][0]][0] or info.get("SILENT", 0) != 0, "SURVIVED")
    mut("right channel read with a stride of 1", "hw_pend[j] = st[2 * j]; }\n					else { for (int j = 0; j < NBANDS; j++) hw_pend[j] = 0; tau_poly_stat_silent++; hw = 0; }", "hw_pend[j] = st[j]; }\n					else { for (int j = 0; j < NBANDS; j++) hw_pend[j] = 0; tau_poly_stat_silent++; hw = 0; }")
    mut("wrong duplicate index dropped", "if (k != 17) w0[j++]", "if (k != 16) w0[j++]")
    mut("last slot of the call never collected", "		if (hw_pend) {\n			if (tau_poly_hw_finish(st))", "		if (0) {\n			if (tau_poly_hw_finish(st))")
    mut("pending slot's PCM written to the current slot", "hw_pend[j] = st[2 * j]; }\n					else { for (int j = 0; j < NBANDS; j++) hw_pend[j] = 0; tau_poly_stat_silent++; hw = 0; }", "pcmBuf[j] = st[2 * j]; }\n					else { for (int j = 0; j < NBANDS; j++) hw_pend[j] = 0; tau_poly_stat_silent++; hw = 0; }")
    i = sbc.index("if (hw && !sbi->hwPolyReady) { tau_poly_hw_clear();", mono_at); j = sbc.index("\n", i)
    exe = build("m_noclear", 1, 1, subband=sbc[:i] + "sbi->hwPolyReady = 1;" + sbc[j:])
    loud = media["mono"][2]                       # noise to the very end: the history left by pass 1 is not silence
    r2, _, _, _ = run(sw, loud, "-1", "0", "-1", "2", "60")      # each pass stops after 60 frames, in the middle of the noise
    two, _, _, _ = run(exe, loud, "-1", "0", "-1", "2", "60")
    good, _, _, _ = run(hw, loud, "-1", "0", "-1", "2", "60")
    check("the clear-mutant comparison is meaningful: the unmutated build equals the reference", good == r2 and len(r2) > 0, "")
    check("mutant killed: a new decoder instance does not clear the unit's history", two != r2, "SURVIVED")
    core = (td / "mp3_poly_model_core.h").read_text()
    assert "#define NFRAC  6" in core
    exe = build("m_shift", 1, 1, core=core.replace("#define NFRAC  6", "#define NFRAC  7"))
    pcm, info, rc, err = run(exe, media["mono"][0])
    check("mutant killed: the unit's output shift is off by one", pcm != refs[media["mono"][0]][0], "SURVIVED")
print("PASSED" if not fails else f"FAILED ({fails})")
sys.exit(1 if fails else 0)
