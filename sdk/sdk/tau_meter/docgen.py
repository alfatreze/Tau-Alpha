"""docs/HOST_TABLE.md, generated from include/tau_meter.h (the structs and their one-line comments) and runner/rv32run.c (which calls count as draw commands), so the reference cannot drift from either.
`tau-meter docs` rewrites it; a test (sim/test_sdk_docs.py) fails when the file differs from what this makes."""
import re
from pathlib import Path
from . import SDK_ROOT

HEADER = SDK_ROOT / "include" / "tau_meter.h"
RUNNER = SDK_ROOT / "runner" / "rv32run.c"
OUT = SDK_ROOT.parent / "docs" / "HOST_TABLE.md"


def struct_fields(text, name):
    m = re.search(r"typedef struct \{(.*?)\} %s;" % name, text, re.S)
    out = []
    for ln in m.group(1).splitlines():
        mm = re.match(r"\s*(?P<decl>[^/]*?;)\s*/\*\s*\[(?P<ver>\d\.\d)\]\s*(?P<doc>.*?)\s*\*/", ln)
        if not mm: continue
        out.append((mm.group("decl").strip(), mm.group("ver"), mm.group("doc")))
    return out


def fnptr(decl):
    m = re.match(r"(?P<ret>[\w ]+?)\s*\(\*(?P<name>\w+)\)\((?P<args>.*)\);", decl)
    return (m.group("name"), "%s %s(%s)" % (m.group("ret").strip(), m.group("name"), m.group("args").strip())) if m else None


def draw_calls():
    """the host-table calls the runner (and so the player's command counter) counts as draw commands"""
    t = RUNNER.read_text()
    names = re.search(r"NAMES\[N_API\] = \{(.*?)\};", t, re.S).group(1)
    names = re.findall(r'"(\w+)"', names)
    draws = [int(x) for x in re.search(r"DRAWS\[N_API\] = \{(.*?)\};", t, re.S).group(1).split(",")]
    return {n for n, d in zip(names, draws) if d}


def render():
    t = HEADER.read_text()
    abi = re.search(r"TAU_METER_ABI_MINOR (\d+)u", t).group(1)
    dc = draw_calls()
    L = ["<!-- generated by `tau-meter docs` from include/tau_meter.h and runner/rv32run.c: do not edit; sim/test_sdk_docs.py fails when this file is stale -->", "# The host table and `mtr_in_t`: reference (ABI 1.%s)" % abi, "",
         "Everything a meter may use is in `include/tau_meter.h`. The player calls `mtr_pack_entry(const mtr_in_t *in, const mtr_host_api_t *api)` once per drawn picture; `TAU_METER(fn)` writes that entry point for you. "
         "Coordinates are pixels of the 400 x 360 screen, colours RGB565. The column **since** is the ABI minor that introduced the entry: a meter that uses a 1.1 or 1.2 entry must say so (`\"abi\": \"1.1\"` in `meter.json`); the suite fails a meter that does not.", "",
         "## `mtr_in_t`: the inputs (read only)", "", "| field | type | since | meaning |", "|---|---|---|---|"]
    for decl, ver, doc in struct_fields(t, "mtr_in_t"):
        ty, names = re.match(r"(.+?)\s+(\*?\w.*);", decl).groups()
        ty = ty.strip()
        for n in [x.strip() for x in names.split(",")]:
            star = "*" if n.startswith("*") else ""
            L.append("| `%s` | `%s%s` | %s | %s |" % (n.lstrip("*"), ty, (" " + star) if star else "", ver, doc.replace("|", "\\|")))
    L += ["", "## `mtr_host_api_t`: the host table", "", "Draw commands (counted against the meter's `cmds` ceiling, one each): %s. The convenience macros `mtr_rect`, `mtr_text`, `mtr_bar`, `mtr_scroll_down`, `mtr_scroll_left`, `mtr_blit`, `mtr_rect_stash` count for you; "
          "for the other draw calls use `tau_meter_cmds++` yourself or accept an undercount (the player counts the engine commands it really executes, not your number)." % ", ".join("`%s`" % n for n in sorted(dc)), "",
          "| entry | signature | since | what it does |", "|---|---|---|---|"]
    for decl, ver, doc in struct_fields(t, "mtr_host_api_t"):
        f = fnptr(decl)
        if f: L.append("| `%s` | `%s` | %s | %s%s |" % (f[0], f[1].replace("|", "\\|"), ver, doc.replace("|", "\\|"), " **(draw command)**" if f[0] in dc else ""))
        else:
            ty, n = re.match(r"(.+?)\s*(\*?\w+);", decl).groups()
            L.append("| `%s` | `%s %s` | %s | %s |" % (n.lstrip("*"), ty.strip(), n, ver, doc.replace("|", "\\|")))
    roles = re.search(r"enum \{(.*?)MTR_ROLE_COUNT", t, re.S).group(1)
    names = re.findall(r"MTR_ROLE_(\w+)", roles)
    L += ["", "## Theme roles (`api->role[MTR_ROLE_*]`)", "", ", ".join("`MTR_ROLE_%s` (%d)" % (n, i) for i, n in enumerate(names)) + ". The colours come from the user's theme and accent; use them instead of fixed colours so the meter follows the theme.", ""]
    L += ["## What a call costs", "", "The suite's cost model (`docs/PERFORMANCE.md`) charges 60 cycles for issuing a draw command and 12 for any other table call, 1.5 cycles per instruction, and 253 cycles for every 32-byte line of code fetched from PSRAM that the 4 KiB "
          "instruction cache does not hold. These are planning numbers, not measurements: the engine's own time (a big fill, a scaled blit) and the player's share of the CPU are not in them. The number that counts is the one the Pocket reports.", ""]
    return "\n".join(L)


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render()); print("wrote %s" % OUT); return 0
