#!/usr/bin/env python3
"""Export the three SDK repositories as plain folders: work/sdk-export/{tau-alpha-meter-sdk, tau-alpha-meter-template, tau-alpha-meters}/ (no network, no git, nothing pushed; creating the public repositories is the owner's step).

  python3 tools/export_sdk.py [OUT_DIR]            default work/sdk-export

  tau-alpha-meter-sdk       sdk/sdk/ + sdk/docs/ + share/ (the seven shipped meters as packages, built by the EXPORTED SDK's own clang recipe, which proves the tree is self-contained)
  tau-alpha-meter-template  sdk/template/
  tau-alpha-meters          sdk/meters/ (regenerated by tools/sdk_collect_meters.py) + dist/<id>.tmeter + SHA256SUMS.txt + index.draft.json + a manual-only CI file
  pocket-test/              tau-meters.bin (the seven shipped meters and a test meter built from the template) for docs/features/meters/SDK_POCKET_TEST.md: a card write needs the owner's approval, nothing is copied anywhere
Needs LLVM (docs/TOOLCHAIN.md)."""
import hashlib, json, shutil, subprocess, sys, tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import sdk_collect_meters as collect
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", "dist", "build", ".DS_Store", "preview.png")
TEST_ID = "5eed0c0de0c0de5eed0c0de0c0de0001"           # the pocket-test meter's id (a fixed test id, not a real author's)


def sh(*a, **kw):
    r = subprocess.run([str(x) for x in a], capture_output=True, text=True, **kw)
    if r.returncode: raise SystemExit("export failed: %s\n%s%s" % (" ".join(map(str, a)), r.stdout, r.stderr))
    return r.stdout


def export(out):
    out = Path(out)
    if out.exists(): shutil.rmtree(out)
    sdk, tpl, col = out / "tau-alpha-meter-sdk", out / "tau-alpha-meter-template", out / "tau-alpha-meters"
    shutil.copytree(ROOT / "sdk/sdk", sdk, ignore=IGNORE); shutil.copytree(ROOT / "sdk/docs", sdk / "docs", ignore=IGNORE)
    shutil.copytree(ROOT / "sdk/template", tpl, ignore=IGNORE)
    with tempfile.TemporaryDirectory() as td:
        collect.collect(td)                                                    # the collection is regenerated, not trusted from the tree
        shutil.copytree(td, col, ignore=IGNORE)
    for n in ("README.md", "INDEX_DRAFT.md"): shutil.copyfile(ROOT / "sdk/meters" / n, col / n)
    shutil.copyfile(ROOT / "sdk/sdk/LICENSE", col / "LICENSE")
    tm = sdk / "tau-meter"
    # the seven shipped meters, built by the exported SDK alone (the collection's own folders)
    (col / "dist").mkdir(); (sdk / "share").mkdir(exist_ok=True)
    rows = []
    for k in collect.KEYS:
        sh(sys.executable, tm, "build", col / k, "--out", col / "dist")
        m = json.loads((col / k / "meter.json").read_text()); p = col / "dist" / (m["id"] + ".tmeter")
        shutil.copyfile(p, sdk / "share" / p.name)
        rows.append({"id": m["id"], "name": m["name"], "version": m["version"], "abi": m["abi"], "tau_min": m.get("tau_min", "0.0"), "params_rev": m["params_rev"], "package": "dist/" + p.name,
                     "sha256": hashlib.sha256(p.read_bytes()).hexdigest(), "size": p.stat().st_size, "author": m["author"], "licence": m["licence"], "source": "meters/" + k})
    (col / "SHA256SUMS.txt").write_text("".join("%s  dist/%s\n" % (r["sha256"], Path(r["package"]).name) for r in rows))
    (col / "index.draft.json").write_text(json.dumps({"schema": 1, "DRAFT": "unsigned example, see INDEX_DRAFT.md; no catalogue exists", "key_id": None, "meters": rows, "revoked": []}, indent=2) + "\n")
    wf = col / ".github/workflows"; wf.mkdir(parents=True)
    (wf / "build.yml").write_text('''# Build every meter with the SDK and run the conformance suite. WRITTEN BUT NOT ACTIVE: manual start only (add push/pull_request triggers to enable).
name: build-and-test
on:
  workflow_dispatch:
jobs:
  build:
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4
      - uses: actions/checkout@v4
        with: { repository: alfatreze/tau-alpha-meter-sdk, path: sdk }
      - run: sudo apt-get update && sudo apt-get install -y clang lld python3
      - run: |
          for d in */meter.json; do dir=$(dirname "$d"); python3 sdk/tau-meter build "$dir" --out dist; done
          for f in dist/*.tmeter; do python3 sdk/tau-meter test "$f" --profile shipped --quick; done
''')
    # the pocket test bin: the seven + a meter built from the template
    pt = out / "pocket-test"; pt.mkdir()
    with tempfile.TemporaryDirectory() as td:
        t = Path(td) / "t"; shutil.copytree(tpl, t, ignore=IGNORE)
        m = json.loads((t / "meter.json").read_text()); m["id"] = TEST_ID; m["name"] = "SDK TEST BARS"; (t / "meter.json").write_text(json.dumps(m, indent=2))
        sh(sys.executable, tm, "build", t, "--out", pt)
    pk = [sdk / "share" / (json.loads((col / k / "meter.json").read_text())["id"] + ".tmeter") for k in collect.KEYS] + [pt / (TEST_ID + ".tmeter")]
    sh(sys.executable, tm, "compose", pt / "tau-meters.bin", *pk)
    (pt / "SHA256SUMS.txt").write_text("%s  tau-meters.bin\n" % hashlib.sha256((pt / "tau-meters.bin").read_bytes()).hexdigest())
    return out


if __name__ == "__main__":
    out = export(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "work/sdk-export")
    for p in sorted(out.iterdir()): print("%s: %d files" % (p, sum(1 for f in p.rglob("*") if f.is_file())))
