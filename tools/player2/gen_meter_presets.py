#!/usr/bin/env python3
"""Generates fw2/generated/meter_presets.h: the presets of the Player 2 meters (Winamp Bars, Winamp Scope, Chladni, Master VU) from meters/<meter>/meter.json, in the manifest's parameter order.
(Layered Wave's come from gen_lw_presets.py.) Usage: gen_meter_presets.py [--check]"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
METERS = [("winamp_bars", "BARS"), ("winamp_scope", "SCOPE"), ("chladni", "CHL"), ("vu_master", "VU")]
HIDE_EXACT = {"scope_trail", "info"}                                   # not drawn in Player 2 (the trail needs the blend; the VU info overlay is not ported)
def hidden(k, p):
    if p.get("experimental"): return 1
    if k in HIDE_EXACT: return 1
    if p["type"] == "u16" and (k.startswith("custom_") or k in ("color_green", "color_yellow", "color_red")): return 1       # raw RGB565 values need a colour picker
    return 0
def descriptors(tag, d):
    keys = [p["key"] for p in d["params"]]; res = []
    for i, p in enumerate(d["params"]):
        k = p["key"]; n = 0; vals = "0"
        if p["type"] == "enum":
            vals = f"mpl_{tag.lower()}_{k}"; res.append(f"static const char *const {vals}[] = {{ " + ", ".join('"%s"' % v.replace("_", " ") for v in p["values"]) + " };"); n = len(p["values"])
        w = p.get("when"); wi, wv = 255, 0
        if isinstance(w, dict) and len(w) >= 1:
            wk, wval = next(iter(w.items()))
            if wk in keys and isinstance(wval, int): wi, wv = keys.index(wk), wval
        ty = {"enum": 1, "bool": 2}.get(p["type"], 0); lo, hi, st = (0, n - 1, 1) if ty == 1 else (0, 1, 1) if ty == 2 else (p["min"], p["max"], p["step"])
        res.append((i, '{ "%s", %d, %d, %d, %d, %d, %d, %s, %d, %d },' % (p["label"].upper(), ty, hidden(k, p), lo, hi, st, n, vals, wi, wv)))
    lines = [x for x in res if isinstance(x, str)]
    rows = [x[1] for x in res if not isinstance(x, str)]
    return lines + [f"static const mpd_t mpd_{tag.lower()}[{len(rows)}] = {{"] + ["    " + r for r in rows] + ["};", f"#define MPD_{tag}_N {len(rows)}u"]
out = ["/* generated by tools/player2/gen_meter_presets.py from the meters directory (each meter.json): do not edit */", "#ifndef P2_METER_PRESETS_H", "#define P2_METER_PRESETS_H", "#include <stdint.h>",
       "#ifndef P2_MPD_T", "#define P2_MPD_T", "/* a parameter the Configure page can edit: type 0 number, 1 choice, 2 on/off; shown only when the parameter `when_idx` has the value `when_val` (255 = always) */", "typedef struct { const char *label; uint8_t type, hidden; uint16_t min, max, step; uint8_t nval; const char *const *vals; uint8_t when_idx; uint16_t when_val; } mpd_t;", "#endif"]
for key, tag in METERS:
    d = json.loads((ROOT / "meters" / key / "meter.json").read_text())
    keys = [p["key"] for p in d["params"]]
    out.append("enum { " + ", ".join(f"MPP_{tag}_{k.upper()}" for k in keys) + f", MPP_{tag}_N }};")
    out.append(f"#define MPP_{tag}_PRESETS {len(d['presets'])}u")
    out.append(f"static const char *const mpp_{tag.lower()}_name[MPP_{tag}_PRESETS] = {{ " + ", ".join('"%s"' % p["name"] for p in d["presets"]) + " };")
    out.append(f"static const uint16_t mpp_{tag.lower()}[MPP_{tag}_PRESETS][MPP_{tag}_N] = {{")
    for p in d["presets"]:
        out.append("    { " + ", ".join(str(p["values"][k]) for k in keys) + f" }},   /* {p['name']} */")
    out.append("};")
    out += descriptors(tag, d)
lw = json.loads((ROOT / "meters/layered_wave/meter.json").read_text())
out += descriptors("LW", lw)
out += ["#endif", ""]
text = "\n".join(out)
dst = ROOT / "fw2/generated/meter_presets.h"
if "--check" in sys.argv:
    ok = dst.exists() and dst.read_text() == text
    print("meter_presets.h up to date" if ok else "meter_presets.h STALE"); sys.exit(0 if ok else 1)
dst.write_text(text)
