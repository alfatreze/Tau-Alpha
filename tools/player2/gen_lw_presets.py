#!/usr/bin/env python3
"""Generates fw2/generated/lw_presets.h: the Layered Wave parameter ids and its non-experimental presets (the first 8 of meters/layered_wave/meter.json, as the old player's generated fw/meters_gen.h holds them).
Usage: gen_lw_presets.py [--check]"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / "fw/meters_gen.h").read_text()
enum = re.search(r"enum \{ (MP_LAYERED_WAVE_VIEW.*?) \};", src).group(1)
ids = [x.strip() for x in enum.split(",")]
assert ids[-1] == "MP_LAYERED_WAVE_N" and len(ids) == 35
names = re.search(r"mtr_pn_layered_wave\[16\] = \{(.*?)\};", src).group(1)
names = re.findall(r'"([^"]+)"', names)
body = re.search(r"mtr_pre_layered_wave\[16 \* MP_LAYERED_WAVE_N\] COLD_DATA = \{(.*?)\n\};", src, re.S).group(1)
rows = [[int(v) for v in re.sub(r"/\*.*?\*/", "", ln).replace(" ", "").strip(",").split(",") if v] for ln in body.strip().splitlines() if ln.strip()]
assert len(rows) == 16 and all(len(r) == 34 for r in rows)
N_STD = 8
out = ["/* generated by tools/player2/gen_lw_presets.py from fw/meters_gen.h (meters/layered_wave/meter.json): do not edit */",
       "#ifndef P2_LW_PRESETS_H", "#define P2_LW_PRESETS_H", "#include <stdint.h>",
       "enum { " + ", ".join(ids[:-1]) + ", MP_LAYERED_WAVE_N };", f"#define LW_PRESET_N {N_STD}u",
       "static const char *const lw_preset_name[LW_PRESET_N] = { " + ", ".join(f'"{n}"' for n in names[:N_STD]) + " };",
       "static const uint16_t lw_preset[LW_PRESET_N][MP_LAYERED_WAVE_N] = {"]
for n, r in zip(names[:N_STD], rows[:N_STD]): out.append("    { " + ", ".join(map(str, r)) + " },   /* " + n + " */")
out += ["};", "#endif", ""]
text = "\n".join(out)
dst = ROOT / "fw2/generated/lw_presets.h"
if "--check" in sys.argv:
    print("lw_presets.h up to date" if dst.exists() and dst.read_text() == text else "lw_presets.h STALE"); sys.exit(0 if dst.exists() and dst.read_text() == text else 1)
dst.write_text(text)
