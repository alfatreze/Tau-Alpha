#!/usr/bin/env python3
"""Generates fw2/generated/sine.h: a 257-entry full-scale sine table (one period in 256 steps plus the wrap entry) for the S3 tone transport. `--check` verifies the committed file."""
import math, sys
from pathlib import Path
OUT = Path(__file__).resolve().parents[2] / "fw2/generated/sine.h"
def text():
    v = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)]
    rows = ["    " + ", ".join(f"{x:6d}" for x in v[i:i + 8]) + "," for i in range(0, 257, 8)]
    return "/* GENERATED by tools/player2/gen_sine.py -- DO NOT EDIT. One period of a full-scale sine in 256 steps plus the wrap entry. */\n#ifndef P2_SINE_H\n#define P2_SINE_H\n#include <stdint.h>\nstatic const int16_t p2_sine[257] = {\n" + "\n".join(rows) + "\n};\n#endif\n"
if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        ok = OUT.exists() and OUT.read_text() == text(); print("sine.h", "up to date" if ok else "STALE"); sys.exit(0 if ok else 1)
    OUT.write_text(text()); print("wrote", OUT)
