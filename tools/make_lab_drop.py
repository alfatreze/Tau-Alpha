#!/usr/bin/env python3
"""A versioned drop of the Meter Lab for Tau Omega (decision D-007, owner 2026-10-26: a pinned copy of tools/meters/preview/ and the committed WebAssembly module, both approved as a documented exception to
"never share literal files"). The drop is a copy of every git-tracked file of tools/meters/preview/ plus MANIFEST.json (the Tau-Alpha commit, every file's SHA-256 and size, the SOUND MAP module's own record of the
sources it was built from) and SHA256SUMS.txt. It is generated, never edited by hand; Tau Omega reads it, verifies it with --check, and keeps its own pinned copy only from a drop like this.

  python3 tools/make_lab_drop.py --out docs/interop/lab-drop/<label>      write a drop (refuses a dirty tools/meters/preview or a stale wasm module)
  python3 tools/make_lab_drop.py --check docs/interop/lab-drop/<label>     verify a drop against its manifest (exit 1 on any difference)
"""
import argparse, base64, hashlib, json, subprocess, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
LAB = "tools/meters/preview"
def sha(b): return hashlib.sha256(b).hexdigest()
def git(*a): return subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, check=True).stdout
def wasm_meta():
    txt = (ROOT / LAB / "meters/sound_map_wasm.js").read_text()
    meta = json.loads(txt[txt.index("/*META") + 6:txt.index("META*/")])
    b64 = txt[txt.index('b64: "') + 6:txt.index('"', txt.index('b64: "') + 6)]
    return meta, base64.b64decode(b64)
def make(out):
    dirty = git("status", "--porcelain", "--", LAB).strip()
    if dirty: sys.exit("refused: tools/meters/preview has uncommitted changes:\n" + dirty)
    out = Path(out)
    if out.exists() and any(out.iterdir()): sys.exit(f"refused: {out} is not empty")
    files = sorted(f for f in git("ls-files", LAB).split("\n") if f)
    meta, wasm = wasm_meta()
    entries = []
    for f in files:
        b = (ROOT / f).read_bytes(); dst = out / "preview" / Path(f).relative_to(LAB); dst.parent.mkdir(parents=True, exist_ok=True); dst.write_bytes(b)
        entries.append({"path": "preview/" + str(Path(f).relative_to(LAB)), "sha256": sha(b), "bytes": len(b)})
    manifest = {"format": 1, "tau_alpha_commit": git("rev-parse", "HEAD").strip(), "source_dir": LAB, "files": entries,
                "wasm": {"module": "preview/meters/sound_map_wasm.js", "wasm_sha256": sha(wasm), "wasm_bytes": len(wasm), "built_from": meta.get("sources", meta)},
                "note": "Generated by tools/make_lab_drop.py. Pinned copy for Tau Omega (D-007). Never edit; ask Tau-Alpha for a new drop."}
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1) + "\n")
    (out / "SHA256SUMS.txt").write_text("".join(f"{e['sha256']}  {e['path']}\n" for e in entries) + f"{sha((out / 'MANIFEST.json').read_bytes())}  MANIFEST.json\n")
    (out / "README.md").write_text("# Meter Lab drop (pinned copy)\n\nGenerated by `tools/make_lab_drop.py` from Tau-Alpha commit `" + manifest["tau_alpha_commit"] + "`. A pinned copy of `tools/meters/preview/` and the committed WebAssembly module of the SOUND MAP, approved by the owner as an exception to \"never share literal files\" (D-007, 2026-10-26). Verify with `python3 tools/make_lab_drop.py --check <this folder>` or `shasum -a 256 -c SHA256SUMS.txt`. Never edit: ask Tau-Alpha for a new drop.\n")
    print(f"drop written to {out}: {len(entries)} files, wasm {len(wasm)} bytes, commit {manifest['tau_alpha_commit'][:8]}")
def check(d):
    d = Path(d); m = json.loads((d / "MANIFEST.json").read_text()); bad = 0
    for e in m["files"]:
        p = d / e["path"]
        if not p.is_file() or sha(p.read_bytes()) != e["sha256"]: print("DIFFERS", e["path"]); bad += 1
    listed = {e["path"] for e in m["files"]}
    for p in (d / "preview").rglob("*"):
        if p.is_file() and str(p.relative_to(d)) not in listed: print("EXTRA", p.relative_to(d)); bad += 1
    sums = (d / "SHA256SUMS.txt").read_text().splitlines()
    if not any(l.endswith("MANIFEST.json") and l.split()[0] == sha((d / "MANIFEST.json").read_bytes()) for l in sums): print("MANIFEST.json does not match SHA256SUMS.txt"); bad += 1
    print("OK: every file matches its manifest" if not bad else f"{bad} problem(s)")
    return 1 if bad else 0
if __name__ == "__main__":
    ap = argparse.ArgumentParser(); g = ap.add_mutually_exclusive_group(required=True); g.add_argument("--out"); g.add_argument("--check")
    a = ap.parse_args(); sys.exit(check(a.check) if a.check else (make(a.out) or 0))
